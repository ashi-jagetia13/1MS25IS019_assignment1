import React, { useState } from 'react';
import { X, Download, Copy, Check, FileText, FileCode, ShieldCheck } from 'lucide-react';
import { QueryResponse, PaperNote } from '../types/research.ts';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  sessionData: QueryResponse | null;
  currentNotes: PaperNote[];
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  sessionData,
  currentNotes,
}) => {
  const [activeTab, setActiveTab] = useState<'markdown' | 'json'>('markdown');
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  // Generate clean Markdown / Text Report
  const generateMarkdownReport = (): string => {
    if (!sessionData) {
      return `# PaperTrail Research Report\n\nNo query has been executed yet.\nActive Paper Notes in Collection: ${currentNotes.length}\n`;
    }

    const dateStr = new Date().toISOString();
    return `# PaperTrail Grounded Synthesis Report
Date: ${dateStr}
Engine Mode: ${sessionData.mode} (${sessionData.model})
Total Latency: ${sessionData.totalLatencyMs}ms
Bounded Steps: ${sessionData.totalSteps}

Notice: All sample notes in this collection are fictional teaching examples demonstrating research methodology, not published empirical papers.

## 1. Research Question
${sessionData.question}

## 2. Grounded Answer
${sessionData.answer}

## 3. Citation Verification
- Cited Source IDs: ${sessionData.citationReport.citedIds.length > 0 ? sessionData.citationReport.citedIds.map(id => `[${id}]`).join(', ') : 'None'}
- Verified Grounded: ${sessionData.citationReport.validCitations.map(id => `[${id}]`).join(', ') || 'None'}
- Ungrounded / Hallucinated: ${sessionData.citationReport.ungroundedCitations.length > 0 ? sessionData.citationReport.ungroundedCitations.map(id => `[${id}]`).join(', ') : 'None (100% Grounded)'}
- Status: ${sessionData.citationReport.isFullyGrounded ? 'VERIFIED: All factual claims cite retrieved documents' : 'WARNING: Unretrieved IDs detected'}

## 4. Retrieved Evidence Cards (${sessionData.evidenceCards.length})
${sessionData.evidenceCards.map((c, idx) => `
### [${idx + 1}] [${c.id}] ${c.title}
- Type: Fictional teaching example — not a published paper
${c.authors ? `- Authors: ${c.authors}\n` : ''}${c.year ? `- Year: ${c.year}\n` : ''}- Overlap Score: ${c.overlap_score} | Matched Tokens: ${c.matched_tokens.join(', ')}
- Excerpt:
> ${c.text}
`).join('\n')}

## 5. Bounded Execution Trace (${sessionData.steps.length} Steps)
${sessionData.steps.map(s => `
- Step ${s.step} [${s.type}]:
  * Action: ${s.toolName ? `${s.toolName}(${JSON.stringify(s.args || {})})` : 'Final Grounded Answer Synthesis'}
  * Observation: ${typeof s.observation === 'object' && s.observation?.message ? s.observation.message : s.text ? 'Grounded answer formulated from retrieved evidence' : 'Completed'}
  * Latency: ${s.latencyMs || 0}ms | Status: ${s.status}
`).join('')}

---
*Generated by PaperTrail. Documents are untrusted; strictly grounded on retrieved evidence.*
`;
  };

  // Generate Clean Structured JSON Export (Guaranteed zero secrets)
  const generateJsonExport = (): string => {
    const exportObject = {
      app: 'PaperTrail',
      version: '1.0.0',
      exportedAt: new Date().toISOString(),
      notice: 'All sample notes in this collection are fictional teaching examples designed to demonstrate research methodology, not published empirical papers.',
      activeNotesCount: currentNotes.length,
      session: sessionData
        ? {
            question: sessionData.question,
            mode: sessionData.mode,
            model: sessionData.model,
            answer: sessionData.answer,
            citationReport: sessionData.citationReport,
            evidenceCards: sessionData.evidenceCards,
            actionTrace: sessionData.steps.map(s => ({
              step: s.step,
              type: s.type,
              action: s.toolName ? { tool: s.toolName, callId: s.callId, args: s.args } : null,
              observation: s.observation || null,
              finalText: s.type === 'final_answer' ? s.text : undefined,
              status: s.status,
              latencyMs: s.latencyMs,
            })),
            totalLatencyMs: sessionData.totalLatencyMs,
          }
        : null,
      notesSnapshot: currentNotes.map(n => ({
        id: n.id,
        title: n.title,
        isTeachingExample: n.isTeachingNote ?? true,
        notice: 'Fictional teaching example — not a published paper',
        category: n.category,
        text: n.text,
      })),
    };
    return JSON.stringify(exportObject, null, 2);
  };

  const currentContent = activeTab === 'markdown' ? generateMarkdownReport() : generateJsonExport();

  const handleCopy = () => {
    navigator.clipboard.writeText(currentContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const filename = activeTab === 'markdown' ? `papertrail-report-${Date.now()}.md` : `papertrail-session-${Date.now()}.json`;
    const mimeType = activeTab === 'markdown' ? 'text/markdown;charset=utf-8' : 'application/json;charset=utf-8';
    const blob = new Blob([currentContent], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 overflow-y-auto bg-stone-900/40 backdrop-blur-xs flex items-center justify-center p-4">
      <div className="bg-[#FAF8F5] border border-[#DCD5C9] rounded-xl shadow-xl w-full max-w-3xl overflow-hidden animate-in fade-in zoom-in-95 duration-150">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-[#E6E1D8] bg-[#F4F0E8]">
          <div className="flex items-center gap-2.5">
            <div className="w-7 h-7 rounded-md bg-[#163326] text-[#E2D8C3] flex items-center justify-center">
              <Download className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-base font-serif font-bold text-[#163326]">
                Export Research Report
              </h3>
              <p className="text-xs text-[#5C6E64]">
                Export synthesis, citations, evidence cards, and action log as Markdown or JSON.
              </p>
            </div>
          </div>

          <button
            type="button"
            onClick={onClose}
            className="text-[#6F8278] hover:text-[#163326] p-1 rounded-md transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6 space-y-4">
          {/* Format selector tabs */}
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-1 p-1 bg-[#ECE6DB] rounded-lg">
              <button
                type="button"
                onClick={() => setActiveTab('markdown')}
                className={`px-3 py-1.5 text-xs font-semibold rounded-md transition-colors flex items-center gap-1.5 cursor-pointer whitespace-nowrap ${
                  activeTab === 'markdown'
                    ? 'bg-white text-[#163326] shadow-xs'
                    : 'text-[#4D6054] hover:text-[#163326]'
                }`}
              >
                <FileText className="w-3.5 h-3.5" />
                <span>Markdown / Text (.md)</span>
              </button>
              <button
                type="button"
                onClick={() => setActiveTab('json')}
                className={`px-3 py-1.5 text-xs font-semibold rounded-md transition-colors flex items-center gap-1.5 cursor-pointer whitespace-nowrap ${
                  activeTab === 'json'
                    ? 'bg-white text-[#163326] shadow-xs'
                    : 'text-[#4D6054] hover:text-[#163326]'
                }`}
              >
                <FileCode className="w-3.5 h-3.5" />
                <span>Structured JSON (.json)</span>
              </button>
            </div>

            {/* Zero-secrets guarantee badge */}
            <div className="flex items-center gap-1.5 text-[11px] font-mono text-emerald-800 bg-emerald-50 border border-emerald-200 px-2.5 py-1 rounded-md">
              <ShieldCheck className="w-3.5 h-3.5 text-emerald-600" />
              <span>Zero secrets in exports</span>
            </div>
          </div>

          {/* Code/Text Preview */}
          <pre className="p-4 bg-white border border-[#D5CEC2] rounded-lg font-mono text-xs text-[#163326] leading-relaxed max-h-80 overflow-y-auto whitespace-pre-wrap select-text">
            {currentContent}
          </pre>

          {/* Action buttons */}
          <div className="flex items-center justify-between pt-4 border-t border-[#E6E1D8]">
            <span className="text-xs text-[#5C6E64]">
              {activeTab === 'markdown' ? 'Formatted for publication & documentation' : 'Full machine-readable session snapshot'}
            </span>

            <div className="flex items-center gap-3">
              <button
                type="button"
                onClick={handleCopy}
                className="px-3.5 py-2 text-xs font-semibold text-[#163326] bg-white border border-[#D5CEC2] hover:bg-stone-50 rounded-lg transition-colors flex items-center gap-1.5 cursor-pointer"
              >
                {copied ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-600" />
                    <span>Copied!</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5" />
                    <span>Copy to Clipboard</span>
                  </>
                )}
              </button>

              <button
                type="button"
                onClick={handleDownload}
                className="px-4 py-2 text-xs font-semibold text-white bg-[#163326] hover:bg-[#1D4233] rounded-lg transition-colors shadow-xs flex items-center gap-1.5 cursor-pointer"
              >
                <Download className="w-3.5 h-3.5" />
                <span>Download File</span>
              </button>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
